"""Bakes the sync program's texts (locales/program/<lang>.json) into sync/locale_data.py, so the exe stays one file.

    python tools/build_locales.py

Each JSON file maps the English source text (which is also the key used in the code) to its translation. The program looks every message up by that text (t / tr)
and shows the English text itself when a translation is missing. Run this after editing a locale file, then rebuild the exe (tools/release.py does it for you)."""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
LANGS = ('zh-Hant', 'zh-Hans', 'ja', 'ko')

data = {}
for lang in LANGS:
    with open(os.path.join(ROOT, 'locales', 'program', lang + '.json'), encoding='utf-8') as f:
        data[lang] = json.load(f)
for lang in LANGS:
    unknown = [k for k in data[lang] if k not in data['zh-Hant']]
    assert not unknown, f'{lang}.json has texts that zh-Hant.json does not: {unknown[:3]}'  # zh-Hant.json lists every source text

out = ['"""Generated by tools/build_locales.py from locales/program/*.json. Do not edit by hand."""', '', 'PROGRAM = {']
for lang in LANGS:
    out.append(f'    {lang!r}: {{')
    for k, v in data[lang].items():
        out.append(f'        {k!r}: {v!r},')
    out.append('    },')
out.append('}')
with open(os.path.join(ROOT, 'sync', 'locale_data.py'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('locale_data.py:', {lang: len(d) for lang, d in data.items()})
